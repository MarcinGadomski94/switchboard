/**
 * D65 (`docs/peers.md` → *Taking a session over*): the pure part of taking a
 * session over from one paired machine to another: the wire shapes both
 * machines' take-over routes speak, matching a session's repos to the target's
 * saved folders by remote URL, the clone decision, the rollback plan, the temp
 * branch names and the texts. No file system, no git, no network: `src/server/takeover/`
 * does the work and calls these.
 */

