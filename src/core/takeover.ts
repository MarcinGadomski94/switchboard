// ── paths (no `node:path`: this module is shared with the UI) ────────────

/** The last segment of a path (either separator). */
function baseName(value: string): string {
  const parts = value.split(/[\\/]+/).filter((part) => part !== '');
  return parts[parts.length - 1] ?? '';
}

/** `parent` + `name` with the separator `parent` uses. */
function joinPath(parent: string, name: string): string {
  const separator = parent.includes('\\') && !parent.includes('/') ? '\\' : '/';
  return `${parent.replace(/[\\/]+$/, '')}${separator}${name}`;
}

// ── names ────────────────────────────────────────────────────────────────

/** The first 8 characters of a session id: the temp branches' namespace. */
export function sessionShortId(sessionId: string): string {
  return sessionId.replace(/[^a-zA-Z0-9]/g, '').slice(0, 8).toLowerCase() || 'session';
}

/** `switchboard/takeover/<session short id>/<branch>`. */
export function tempBranchName(sessionId: string, branch: string): string {
  return `${TAKEOVER_BRANCH_PREFIX}${sessionShortId(sessionId)}/${branch}`;
}

/** `true` for a branch name in the take-over namespace (the only ones the cleanup routes delete). */
export function isTempBranch(branch: string): boolean {
  return branch.startsWith(TAKEOVER_BRANCH_PREFIX) && !branch.includes('..') && !branch.includes(' ') && !branch.endsWith('/');
}

// ── remote URLs ──────────────────────────────────────────────────────────

/**
 * A remote URL without credentials: `https://user:token@host/x.git` →
 * `https://host/x.git` (an ssh URL's user, `git@`, is not a secret and stays).
 */
export function redactUrl(url: string): string {
  const text = url.trim();
  const match = /^([a-z][a-z0-9+.-]*):\/\/([^/@]*)@(.*)$/i.exec(text);
  if (!match) return text;
  const scheme = (match[1] as string).toLowerCase();
  if (scheme === 'ssh' || scheme === 'git+ssh') return text;
  return `${match[1]}://${match[3]}`;
}

/**
 * What two clones of one repo have in common: the remote URL without scheme,
 * credentials, default port, `.git` and a trailing slash, the host lower-cased
 * (`git@github.com:acme/app.git`, `https://user@GitHub.com/acme/app` and
 * `ssh://git@github.com:22/acme/app.git/` all give `github.com/acme/app`). A local
 * path or `file://` URL (a bare repo on disk) gives its path with forward slashes.
 */
export function normalizeRemoteUrl(url: string): string {
  let text = url.trim();
  if (text === '') return '';
  const strip = (value: string): string => value.replace(/\/+$/, '').replace(/\.git$/i, '').replace(/\/+$/, '');
  // A Windows drive path (`C:\repos\app.git`).
  if (/^[A-Za-z]:[\\/]/.test(text)) return strip(`${text.slice(0, 1).toLowerCase()}${text.slice(1).replace(/\\/g, '/')}`);
  const scheme = /^([a-z][a-z0-9+.-]*):\/\/(.*)$/i.exec(text);
  if (scheme) {
    const kind = (scheme[1] as string).toLowerCase();
    let rest = scheme[2] as string;
    if (kind === 'file') {
      rest = rest.replace(/^localhost(?=\/)/i, '');
      if (/^\/[A-Za-z]:\//.test(rest)) rest = rest.slice(1);
      return strip(rest.replace(/\\/g, '/'));
    }
    const at = rest.indexOf('@');
    const slash = rest.indexOf('/');
    if (at >= 0 && (slash < 0 || at < slash)) rest = rest.slice(at + 1);
    const cut = rest.indexOf('/');
    let host = cut < 0 ? rest : rest.slice(0, cut);
    const tail = cut < 0 ? '' : rest.slice(cut);
    const defaults: Record<string, string> = { https: '443', http: '80', ssh: '22', 'git+ssh': '22', git: '9418' };
    host = host.toLowerCase();
    const port = /:(\d+)$/.exec(host);
    if (port && defaults[kind] === port[1]) host = host.slice(0, host.length - (port[0] as string).length);
    return strip(`${host}${tail}`);
  }
  // scp-like `user@host:owner/repo.git`.
  const scp = /^(?:[^@/\s]+@)?([^:/\s]+):(?!\/\/)(.*)$/.exec(text);
  if (scp) return strip(`${(scp[1] as string).toLowerCase()}/${(scp[2] as string).replace(/^\/+/, '')}`);
  // A POSIX path.
  text = text.replace(/\\/g, '/');
  return strip(text);
}

// ── planning ─────────────────────────────────────────────────────────────

/** Options of {@link planRepos}. */
export interface PlanOptions {
  /** `clonePaths[key]`: where the developer asked a missing repo to be cloned. */
  readonly clonePaths?: Readonly<Record<string, string>>;
  /** The session's name (a worktree session gets `../<repo>-wt-<name>` for it). */
  readonly sessionName: string;
  /** The parent of default clone folders (next to the target's default folder); `null` = none known. */
  readonly defaultCloneParent: string | null;
  /** Paths that exist already on the target (a worktree or clone path that collides is blocked). */
  readonly exists?: ReadonlySet<string>;
  /** Branches checked out in another worktree of a candidate repo: `<path>\n<branch>`. */
  readonly checkedOut?: ReadonlySet<string>;
  /** Repos whose working tree is not clean on the target (a main-checkout session cannot check a branch out there): their paths. */
  readonly dirtyTargets?: ReadonlySet<string>;
  /** The path of a worktree (`worktreePath` of `src/core/worktrees.ts`; passed so this module stays free of it). */
  readonly worktreePathOf: (repoPath: string, sessionName: string) => string;
}

/** The candidates that match `repo` by remote, best first (the one named like the repo, then by path). */
export function matchingCandidates(repo: Pick<SourceRepo, 'name' | 'remoteKey'>, candidates: readonly TargetCandidate[]): TargetCandidate[] {
  return candidates
    .filter((candidate) => candidate.remoteKey !== null && candidate.remoteKey !== '' && candidate.remoteKey === repo.remoteKey)
    .sort((a, b) => Number(baseName(b.path) === repo.name) - Number(baseName(a.path) === repo.name) || a.path.localeCompare(b.path));
}

/**
 * Decides, for each of the session's repos, what the target does: use the saved
 * repo that has the same remote (an existing worktree of it counts as the repo:
 * the main checkout is what is matched), clone it (a path to ask for), or refuse
 * (a path that exists, a branch checked out elsewhere, a dirty checkout). Pure.
 */
export function planRepos(repos: readonly SourceRepo[], candidates: readonly TargetCandidate[], options: PlanOptions): RepoResolution[] {
  const exists = options.exists ?? new Set<string>();
  const checkedOut = options.checkedOut ?? new Set<string>();
  const dirty = options.dirtyTargets ?? new Set<string>();
  return repos.map((repo): RepoResolution => {
    const base = { key: repo.key, name: repo.name, branch: repo.branch, uncommitted: repo.dirty.total, ahead: repo.ahead };
    const blocked = (reason: string, extra: Partial<RepoResolution> = {}): RepoResolution => ({
      ...base,
      action: 'blocked',
      matchedPath: null,
      folderId: null,
      worktreePath: null,
      cloneTo: null,
      cloneUrl: null,
      reason,
      summary: reason,
      ...extra,
    });
    if (repo.remoteKey === '') return blocked(`${repo.name} has no remote: its work can only travel through a shared remote`);
    const match = matchingCandidates(repo, candidates)[0];
    if (match) {
      const wantsWorktree = repo.kind === 'worktree';
      const worktreePath = wantsWorktree ? options.worktreePathOf(match.path, options.sessionName) : null;
      if (worktreePath !== null && exists.has(worktreePath)) return blocked(`${worktreePath} exists already on the target`, { matchedPath: match.path, folderId: match.folderId });
      if (checkedOut.has(`${match.path}\n${repo.branch}`)) {
        return blocked(`the branch ${repo.branch} is checked out in another worktree of ${match.path}`, { matchedPath: match.path, folderId: match.folderId });
      }
      if (!wantsWorktree && dirty.has(match.path)) {
        return blocked(`${match.path} has uncommitted changes on the target: commit or stash them first`, { matchedPath: match.path, folderId: match.folderId });
      }
      return {
        ...base,
        action: 'use',
        matchedPath: match.path,
        folderId: match.folderId,
        worktreePath,
        cloneTo: null,
        cloneUrl: null,
        reason: null,
        summary: worktreePath ? `Use ${match.path}; new worktree ${worktreePath} on ${repo.branch}` : `Use ${match.path}; check out ${repo.branch}`,
      };
    }
    const typed = options.clonePaths?.[repo.key]?.trim();
    const cloneTo = typed && typed !== '' ? typed : options.defaultCloneParent ? joinPath(options.defaultCloneParent, repo.name) : null;
    if (cloneTo === null) return blocked(`${repo.name} is not on this machine and no folder is known to clone it into: type one`);
    if (exists.has(cloneTo)) return blocked(`${cloneTo} exists already: choose another folder to clone ${repo.name} into`, { cloneTo, cloneUrl: repo.remoteUrl });
    return {
      ...base,
      action: 'clone',
      matchedPath: null,
      folderId: null,
      worktreePath: repo.kind === 'worktree' ? options.worktreePathOf(cloneTo, options.sessionName) : null,
      cloneTo,
      cloneUrl: repo.remoteUrl,
      reason: null,
      summary: `Not on this machine: clone ${repo.remoteUrl} into ${cloneTo}`,
    };
  });
}

/** What the take-over as a whole refuses on the target, given the resolutions. */
export function planBlockers(resolutions: readonly RepoResolution[]): string[] {
  const out: string[] = [];
  for (const resolution of resolutions) if (resolution.action === 'blocked' && resolution.reason) out.push(resolution.reason);
  return out;
}

// ── rollback ─────────────────────────────────────────────────────────────

/** What had happened when a take-over failed. */
export interface RollbackState {
  /** The steps that finished. */
  readonly done: readonly TakeoverStepId[];
  /** Step 2 stopped a live process of a Switchboard-run session. */
  readonly stoppedLive: boolean;
  /** The session is a hooked terminal session. */
  readonly hooked: boolean;
  /** The hooked terminal's `claude` was stopped. */
  readonly terminalStopped: boolean;
}

/** One undo action, run in the order given. */
export type RollbackAction =
  | 'target-undo-apply'
  | 'target-remove-session'
  | 'target-remove-files'
  | 'source-delete-temp-branches'
  | 'source-resume'
  | 'source-note-terminal-stopped';

/**
 * The undo actions for a failure after `state.done`: the target first (its
 * working tree, then the copied conversation), then the source (the temporary
 * branches, then the session's process). A failure at step 6 or earlier undoes
 * everything; the source's own work tree was never touched (the WIP commit is
 * made without moving the branch or the index), so "undo the WIP commit" is
 * deleting the temp branches. A hooked terminal's stopped `claude` cannot be
 * started again from here: the note says how to resume it.
 */
export function rollbackActions(state: RollbackState): RollbackAction[] {
  const has = (step: TakeoverStepId): boolean => state.done.includes(step);
  const actions: RollbackAction[] = [];
  if (has('resume')) actions.push('target-remove-session');
  if (has('apply') || has('resume')) actions.push('target-undo-apply');
  if (has('transfer') || has('apply') || has('resume')) actions.push('target-remove-files');
  if (has('capture') || has('transfer') || has('apply') || has('resume')) actions.push('source-delete-temp-branches');
  if (state.hooked && state.terminalStopped) actions.push('source-note-terminal-stopped');
  else if (!state.hooked && state.stoppedLive) actions.push('source-resume');
  return actions;
}

